function Ax = build_Ax2(parh, par0, x, model)
% Ax = build_Ax2(parh, par0, x, model)
%
% Computes A x where A is the operator mapping a set of magnetic elements
% to the normal component of the magnetic field they generate on some
% regular rectangular grids at heights given on parh.h.
%
% More precisely, we consider a regular rectangular grid with lower-left
% corner at position (xh, yh, h) where (xh, yh)=rh, with step size deltah_x
% along the x-axis and deltah_y along the y-axis, where
% (deltah_x, deltah_y)=deltah and with nhx points along the x-axis and nhy
% points along the y-axis where (nhx, nhy) = nh.
%
% We also consider a list of integer coordinates Ind, i.e. Ind has ns rows
% and 2 columns and the i-th row of Ind is (Ind_i1, Ind_i2) where
% (Ind_i1, Ind_i2) denotes the integer coordinates of a point on a grid at
% height 0. This grid has origin at position (x0, y0, 0) where
% (x0, y0)=r0 and has step size Nx*deltah_x along the x-axis and
% Ny*deltah_y along the y-axis, where (Nx,Ny)=N.
% The element listed at the i-th row of Ind is hence at position
%   ( x0+(Ind_i1-1)*Nx*deltah_x, y0+(Ind_i2-1)*Ny*deltah_y, 0).
%
% Notice that negative integer coordinates are allowed in Ind.
%
% x is a vector of the form (m11; ... mns1; m12 ... mns2; m13 ... mns3).
% The operator A maps such a vector to the normal component of the magnetic
% field generated by a set of ns elements positioned at points with integer
% coordinates (Ind_i1, Ind_i2), where i ranges from 1 to ns, where the i-th
% element has moment (mi1 mi2 mi3). The field being measured at all points
% of the grid of height h.
%
% Elements may be dipoles, uniformly magnetized rectangles or uniformly 
% magnezatized parallelepipeds. This can be set using the 'model' variable:
% model = 'dipole' | 'rect' | 'para'. 
% Default is 'dipole'.
%
% Note that for the 'para' model it is necessary for the variable par0 to
% have the field "delta0".
%
% The vector A x has hence size nh(1)*nh(2) elements and is returned in
% variable Ax.
%
% CREATED 20191024 based on "build_Ax_frac" with the following differences 
%
%   1.- It take parameters "parh", "par0", instead of the classical ones
%   2.- It can handle when "parh.h" is a vector for when the magnetic field
%       is measured on more than one plane
%
% CHANGELOG
% 20231022
%   1.- Fixed the use of N on line 74
% 20211008
%   1.- Added an error when the "model" variable is not set to the
%       supported vales.
%   2.- Added support of the "'para'" model when still the
%       magnetization is on a 2d grid.
% 20220506
%   1.- To avoid using the signal toolbox I added a conditon that will only
%       call it if necessary
% 20220701
%   1.- Added support in the case when par0 has delta0 but not N



rh     = parh.rh;
nh     = parh.nh;
deltah = parh.deltah;
hvec   = parh.h;
r0     = par0.r0;
Ind    = par0.Ind;

if isfield(par0,'delta0')
    delta0 = par0.delta0;
    N      = delta0./deltah;
    if isfield(par0,'N') && ~isequal(N,par0.N)
        error('N and delta0 from par0 are not consistent')
    end
else
    N      = par0.N;
    delta0 = deltah.*N;
end

[N,D] = rat(N);     %
nh = D.*nh;         %
deltah=deltah./D;   %

if strcmp(model, 'para') && isfield(par0,'delta0')
    delta0 = par0.delta0;
elseif strcmp(model, 'para') && ~isfield(par0,'delta0')
    error('For the parallelepiped model, "delta0" must be a field of "par0"')
end



ns = size(Ind, 1);
[xaxish, yaxish, ~]=grid_Ndelta(nh, deltah, rh);
[X, Y] = meshgrid(xaxish, yaxish);


n  = prod(nh);
Ax = [];

for h=hvec

    Axh = zeros(n, size(x, 2));
    
    for ell=1:ns
        i=Ind(ell,:);
        if nargin <= 3
            [B1, B2, B3] = Bz_dipole(X-(r0(1)+(i(1)-1).*delta0(1)), ...
                Y-(r0(2)+(i(2)-1).*delta0(2)), h);
        elseif strcmp(model, 'rect')
            [B1, B2, B3] = Bz_rect(X-(r0(1)+(i(1)-1).*delta0(1)), ...
                Y-(r0(2)+(i(2)-1).*delta0(2)), h, delta0);
        elseif strcmp(model, 'para')
            [B1, B2, B3] = Bz_parallelepiped(...
                X-(r0(1)+(i(1)-1).*delta0(1)), ...
                Y-(r0(2)+(i(2)-1).*delta0(2)), h, delta0);
        elseif strcmp(model, 'dipole')
            [B1, B2, B3] = Bz_dipole(X-(r0(1)+(i(1)-1).*delta0(1)), ...
                Y-(r0(2)+(i(2)-1).*delta0(2)), h);
        else
            error('The value for the variable "model" is not supported')
        end
        
        Axh = Axh + reshape(B1, n, 1)*x(ell, :) + ...
                    reshape(B2, n, 1)*x(ell+ns, :) + ...
                    reshape(B3, n, 1)*x(ell+2*ns, :);
    end
    
    Bz  = reshape(Axh,fliplr(nh));                           %
    if D(1)~=1 && D(2)~=1
        Bz  = downsample(downsample(Bz,D(2))',D(1))';     %
    end
    Axh = reshape(Bz,[],1);                        %
    
    Ax = [Ax;Axh]; %#ok<AGROW>
    
end
 

end

